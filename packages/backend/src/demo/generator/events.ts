export interface Currency {
  readonly code: string;
  /** Units per euro. */
  readonly rate: number;
}

/** A holiday: travel booked ahead, accommodation, spending abroad and what went wrong. */
export interface Trip {
  readonly start: string;
  readonly nights: number;
  readonly destination: string;
  /** The currency of card payments abroad; null within the euro area. */
  readonly currency: Currency | null;
  readonly carrier: string;
  /** Total travel cost (all travellers), negative euros. */
  readonly travel: number;
  readonly lodging: string;
  /** Negative euros for the whole stay. */
  readonly lodgingCost: number;
  readonly spots: readonly string[];
  readonly mishaps?: readonly TripMishap[];
}

export interface TripMishap {
  /** Days after the start. */
  readonly offset: number;
  readonly euros: number;
  readonly name: string;
  readonly zweck: string;
  readonly category: CategoryKey;
  readonly kommentar?: string;
}

