import {
  ChangeDetectionStrategy,
  Component,
  computed,
  inject,
  input,
  output,
  signal,
  type Signal,
} from '@angular/core';
import type {
  KeyMode,
  UserKeyCreateRequest,
  UserKeyCreateResponse,
} from '@hibiscus-frontend/shared/contracts/user';
import type { TranslationKey } from '../../../core/models/translation.model';
import { ApiService } from '../../../core/services/api.service';
import { TranslationService } from '../../../core/services/translation.service';
import { userErrorOf } from '../../../core/utils/user-errors';
import { isKeyFormat } from '../../key/key-format';
import { KeyRevealComponent } from '../key-reveal/key-reveal.component';

type Source = 'generate' | 'own';

/**
 * Sets the user's first key: generated by the server and shown once, or pasted. Emits `created`
 * once the key exists and, for a generated one, the user confirmed they saved it.
 */
@Component({
  selector: 'app-key-create',
  templateUrl: './key-create.component.html',
  styleUrl: './key-create.component.scss',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [KeyRevealComponent],
})
export class KeyCreateComponent {
  private readonly api = inject(ApiService);
  protected readonly i18n = inject(TranslationService);

  /** The key mode the key is created with. */
  readonly mode = input.required<KeyMode>();
  readonly created = output<void>();

  protected readonly source = signal<Source>('generate');
  protected readonly own = signal('');
  protected readonly showProblem = signal(false);
  protected readonly working = signal(false);
  protected readonly error = signal<TranslationKey | null>(null);
  /** The generated key; held only while it is shown, never stored anywhere else. */
  protected readonly revealed = signal<string | null>(null);

  protected readonly ownValid: Signal<boolean> = computed(() => isKeyFormat(this.own()));

  protected pick(source: Source): void {
    this.source.set(source);
    this.error.set(null);
  }

  protected onOwn(event: Event): void {
    if (!(event.target instanceof HTMLInputElement)) throw new Error('Expected an input event');
    this.own.set(event.target.value);
  }

  protected submit(): void {
    if (this.working()) return;
    const own: boolean = this.source() === 'own';
    if (own) {
      this.showProblem.set(true);
      if (!this.ownValid()) return;
    }
    const request: UserKeyCreateRequest = own
      ? { mode: this.mode(), key: this.own().trim() }
      : { mode: this.mode() };
    this.working.set(true);
    this.error.set(null);
    this.api.createUserKey(request).subscribe({
      next: (response: UserKeyCreateResponse): void => {
        this.working.set(false);
        if (own) {
          this.own.set('');
          this.created.emit();
          return;
        }
        this.revealed.set(response.key);
      },
      error: (failure: unknown): void => {
        this.working.set(false);
        this.error.set(
          userErrorOf(failure) === 'key-configured' ? 'keyCreate.configured' : 'keyCreate.failed',
        );
      },
    });
  }

  protected acknowledged(): void {
    this.revealed.set(null);
    this.created.emit();
  }
}
